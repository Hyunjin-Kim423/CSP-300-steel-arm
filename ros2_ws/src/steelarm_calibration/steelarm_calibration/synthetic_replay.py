"""Publish a deterministic, explicitly synthetic AprilTag frame for Jazzy integration tests."""
from pathlib import Path
import rclpy
from rclpy.node import Node
from sensor_msgs.msg import Image, CameraInfo
from geometry_msgs.msg import PoseStamped
class SyntheticReplay(Node):
 def __init__(self):
  super().__init__('synthetic_apriltag_replay'); self.declare_parameter('image_path',''); self.declare_parameter('rate_hz',10.0)
  path=Path(self.get_parameter('image_path').value)
  if not path.is_file(): raise RuntimeError(f'Synthetic image not found: {path}')
  raw=path.read_bytes(); header,pixels=raw.split(b'\n255\n',1); tokens=header.split()
  if tokens[0] != b'P5': raise RuntimeError('Expected binary PGM (P5) generated by generate_synthetic_tag.py')
  self.width,self.height=int(tokens[-2]),int(tokens[-1]); self.pixels=pixels
  self.image_pub=self.create_publisher(Image,'/synthetic/camera/image_rect',10); self.info_pub=self.create_publisher(CameraInfo,'/synthetic/camera/camera_info',10); self.pose_pub=self.create_publisher(PoseStamped,'/synthetic/camera/pose',10)
  self.create_timer(1.0/self.get_parameter('rate_hz').value,self.publish); self.get_logger().info('TEST ONLY: synthetic tag36h11 ID 0 replay.')
 def publish(self):
  stamp=self.get_clock().now().to_msg(); frame='synthetic_camera_optical'; image=Image(); image.header.stamp=stamp; image.header.frame_id=frame; image.width=self.width; image.height=self.height; image.encoding='mono8'; image.step=self.width; image.data=self.pixels
  info=CameraInfo(); info.header=image.header; info.width=self.width; info.height=self.height; info.distortion_model='plumb_bob'; info.d=[0.]*5; info.k=[600.,0.,320.,0.,600.,240.,0.,0.,1.]; info.r=[1.,0.,0.,0.,1.,0.,0.,0.,1.]; info.p=[600.,0.,320.,0.,0.,600.,240.,0.,0.,0.,1.,0.]
  pose=PoseStamped(); pose.header=image.header; pose.pose.orientation.w=1.; self.image_pub.publish(image); self.info_pub.publish(info); self.pose_pub.publish(pose)
def main():
 rclpy.init(); node=SyntheticReplay()
 try: rclpy.spin(node)
 except KeyboardInterrupt: pass
 finally:
  node.destroy_node()
  if rclpy.ok(): rclpy.shutdown()
